// функция принимает на вход опциональное замыкание и целое число, выполняет замыкание только. в случае если число больше 0

func checker(_ closure: (() -> Void)?, _ number: Int){
    guard number > 0, let closure else { return }
    closure()
}
print(checker({print("Hello World!")}, 2))

//  функция принимает число на вход (год), проверить високосный ли он

func isLeapYear(_ year: Int) -> Bool {
    guard year > 0 else { return false }
    guard ((year % 4) == 0) else { return false }
    guard (year % 100 != 0 || year % 400 == 0) else { return false }
    return true
}

print(isLeapYear(2025))
print(isLeapYear(2012))
